@pytest.mark.parametrize("argv", REFUSED, ids=lambda a: " ".join(a)[:40] or "empty")
def test_refused(argv: list[str]) -> None:
    assert destructive_reason(argv) is not None


@pytest.mark.parametrize("argv", ALLOWED, ids=lambda a: " ".join(a)[:40])
def test_not_flagged(argv: list[str]) -> None:
    assert destructive_reason(argv) is None
