"""Prepare the local lab: keys, pinned host keys, sudo rules and the inventory.

Run once from the repository root:
    python lab/setup_lab.py
    docker compose -f lab/docker-compose.yml --profile build build base
    docker compose -f lab/docker-compose.yml up -d --build
    uv run wheelhouse --inventory lab/wheelhouse.lab.yaml hosts

Everything it writes is lab-only and git-ignored (lab/.secrets, lab/wheelhouse.lab.yaml).
Safe to run again: existing keys are kept.
"""

from __future__ import annotations

import secrets
import shutil
import subprocess
import sys
from pathlib import Path

LAB = Path(__file__).resolve().parent
SECRETS = LAB / ".secrets"

# name: (ssh port on 127.0.0.1, role, services Wheelhouse may restart/start/stop)
HOSTS: dict[str, tuple[int, str, tuple[str, ...]]] = {
    "web01": (2211, "web", ("nginx",)),
    "app01": (2212, "app", ("orders-api", "memcached")),
    "db01": (2213, "database", ("mariadb",)),
    "mq01": (2214, "queue", ("rabbitmq-server",)),
    "etl01": (2215, "etl", ("orders-daily",)),
}

# Extra read-only commands that need root, per host (exact command lines for sudoers).
EXTRA_SUDO: dict[str, tuple[str, ...]] = {
    "mq01": ("/usr/sbin/rabbitmqctl list_queues -p / name messages consumers",),
}


def keygen(path: Path, comment: str) -> None:
    if path.exists():
        return
    ssh_keygen = shutil.which("ssh-keygen")
    if ssh_keygen is None:
        sys.exit("ssh-keygen not found. Install OpenSSH (Windows: Settings > Optional features).")
    subprocess.run(  # noqa: S603
        [ssh_keygen, "-q", "-t", "ed25519", "-N", "", "-C", comment, "-f", str(path)],
        check=True,
    )


def sudoers(host: str, services: tuple[str, ...]) -> str:
    cmds = [
        f"/usr/bin/systemctl {verb} {svc}"
        for svc in services
        for verb in ("restart", "start", "stop")
    ]
    cmds += EXTRA_SUDO.get(host, ())
    return (
        "# Lab only. Exact commands Wheelhouse may run as root on this host.\n"
        f"wheelhouse ALL=(root) NOPASSWD: {', '.join(cmds)}\n"
    )


def main() -> None:
    """Each host gets only its own files (.secrets/hosts/<name>), so root on one lab host
    cannot read another host's keys, the client's private key or the ledger."""
    (SECRETS / "hostkeys").mkdir(parents=True, exist_ok=True)
    keygen(SECRETS / "wheelhouse_ed25519", "wheelhouse-lab-client")
    client_pub = (SECRETS / "wheelhouse_ed25519.pub").read_text().strip()

    known: list[str] = []
    for name, (port, _role, services) in HOSTS.items():
        key = SECRETS / "hostkeys" / f"{name}_ed25519"
        keygen(key, f"{name}-lab-host")
        pub = key.with_suffix(".pub").read_text().split()
        known.append(f"[127.0.0.1]:{port} {pub[0]} {pub[1]}")
        own = SECRETS / "hosts" / name
        own.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(key, own / "ssh_host_ed25519_key")
        shutil.copyfile(key.with_suffix(".pub"), own / "ssh_host_ed25519_key.pub")
        # restrict: no forwarding, no TTY, no ~/.ssh/rc for this key.
        (own / "authorized_keys").write_text(f"restrict {client_pub}\n", newline="\n")
        (own / "sudoers").write_text(sudoers(name, services), newline="\n")
    (SECRETS / "known_hosts").write_text("\n".join(known) + "\n", newline="\n")

    # The lab ETL job's database password: generated here, never in the repository.
    # db01 gets it to create the account; etl01 gets a client config with it.
    pw_file = SECRETS / "etl_password"
    if not pw_file.exists():
        pw_file.write_text(secrets.token_urlsafe(24), newline="\n")
    password = pw_file.read_text().strip()
    (SECRETS / "hosts" / "db01" / "etl_password").write_text(password, newline="\n")
    (SECRETS / "hosts" / "etl01" / "etl.cnf").write_text(
        "[client]\nhost=db01\nuser=etl\npassword=" + password + "\n", newline="\n"
    )

    lines = [
        "# Lab inventory, generated by lab/setup_lab.py. Paths are relative to this file.",
        "known_hosts: .secrets/known_hosts",
        "ledger: .secrets/ledger.jsonl",
        "sudo_users: [root]",
        "limits:",
        "  actions_per_minute: 60",
        "hosts:",
    ]
    for name, (port, role, services) in HOSTS.items():
        lines += [
            f"  {name}:",
            "    address: 127.0.0.1",
            f"    port: {port}",
            "    user: wheelhouse",
            "    identity_file: .secrets/wheelhouse_ed25519",
            f"    role: {role}",
            f"    services: [{', '.join(services)}]",
        ]
    (LAB / "wheelhouse.lab.yaml").write_text("\n".join(lines) + "\n", newline="\n")
    print(f"lab secrets in {SECRETS}")
    print(f"inventory: {LAB / 'wheelhouse.lab.yaml'}")


if __name__ == "__main__":
    main()
